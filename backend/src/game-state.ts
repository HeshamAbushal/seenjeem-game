export enum GameStage {
  LOBBY = 'LOBBY',
  BOARD = 'BOARD',
  QUESTION_ACTIVE = 'QUESTION_ACTIVE',
  BUZZED_IN = 'BUZZED_IN',
  ANSWER_REVEAL = 'ANSWER_REVEAL',
  GAME_OVER = 'GAME_OVER'
}

export interface Team {
  id: 'team_1' | 'team_2';
  name: string;
  leaderSocketId: string | null;
  score: number;
}

export interface Question {
  id: string;
  category: string;
  points: number;      // 10, 20, 30
  questionText: string;
  options: string[];   // A, B, C, D
  correctOptionIndex: number; // 0 to 3
  played: boolean;
}

export type GameMode = 'MULTIPLE_CHOICE' | 'OPEN_QUESTION';

export interface GameState {
  roomId: string;
  gameMode: GameMode;
  stage: GameStage;
  teams: {
    team_1: Team;
    team_2: Team;
  };
  categories: string[];
  questions: { [id: string]: Question };
  activeQuestionId: string | null;
  selectingTeamId: 'team_1' | 'team_2';
  buzzedTeamId: 'team_1' | 'team_2' | null;
  buzzTimeRemaining: number;
  answerTimeRemaining: number | null;
  isStealTurn: boolean;
  isOpenAnswerRevealed?: boolean;
  winnerTeamId: 'team_1' | 'team_2' | null;
}

// 6 categories, each with 2 Easy (10pts), 2 Medium (20pts), 2 Hard (30pts) = 36 questions
const MOCK_CATEGORIES = [
  'فلوقات أبو سعيد',
  'كود وببجي وشلة الألعاب',
  'تحديات الأكل والعقابات',
  'معلومات عامة وثقافة',
  'مقولات أبو سعيد الخالدة',
  'أسئلة شاطحة وسريعة'
];

export function createInitialState(roomId: string): GameState {
  const questions: { [id: string]: Question } = {};

  MOCK_CATEGORIES.forEach((category, catIdx) => {
    // 2 Easy (10 points)
    for (let q = 1; q <= 2; q++) {
      const qId = `cat_${catIdx}_10_${q}`;
      questions[qId] = {
        id: qId,
        category,
        points: 10,
        questionText: getQuestionText(catIdx, 10, q),
        options: getOptions(catIdx, 10, q),
        correctOptionIndex: getCorrectOption(catIdx, 10, q),
        played: false
      };
    }
    // 2 Medium (20 points)
    for (let q = 1; q <= 2; q++) {
      const qId = `cat_${catIdx}_20_${q}`;
      questions[qId] = {
        id: qId,
        category,
        points: 20,
        questionText: getQuestionText(catIdx, 20, q),
        options: getOptions(catIdx, 20, q),
        correctOptionIndex: getCorrectOption(catIdx, 20, q),
        played: false
      };
    }
    // 2 Hard (30 points)
    for (let q = 1; q <= 2; q++) {
      const qId = `cat_${catIdx}_30_${q}`;
      questions[qId] = {
        id: qId,
        category,
        points: 30,
        questionText: getQuestionText(catIdx, 30, q),
        options: getOptions(catIdx, 30, q),
        correctOptionIndex: getCorrectOption(catIdx, 30, q),
        played: false
      };
    }
  });

  return {
    roomId,
    gameMode: 'MULTIPLE_CHOICE',
    stage: GameStage.LOBBY,
    teams: {
      team_1: { id: 'team_1', name: 'شقردية أبو سعيد', leaderSocketId: null, score: 0 },
      team_2: { id: 'team_2', name: 'سناعيس الكرو', leaderSocketId: null, score: 0 }
    },
    categories: MOCK_CATEGORIES,
    questions,
    activeQuestionId: null,
    selectingTeamId: 'team_1',
    buzzedTeamId: null,
    buzzTimeRemaining: 20,
    answerTimeRemaining: 12,
    isStealTurn: false,
    isOpenAnswerRevealed: false,
    winnerTeamId: null
  };
}

